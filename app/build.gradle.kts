import java.util.Properties

plugins {
    alias(libs.plugins.android.application)
    alias(libs.plugins.kotlin.compose)
    alias(libs.plugins.kotlin.serialization)
}

// 发布签名凭据放在工程根目录的 keystore.properties（已在 .gitignore 中忽略），
// 内容格式见 docs/signing.md。文件不存在时 release 仍可构建，只是产出未签名 APK。
val keystorePropsFile = rootProject.file("keystore.properties")
val keystoreProps = Properties().apply {
    if (keystorePropsFile.exists()) {
        keystorePropsFile.inputStream().use { load(it) }
    }
}

android {
    namespace = "com.timelock.app"
    compileSdk = 37

    defaultConfig {
        applicationId = "com.timelock.app"
        minSdk = 26
        targetSdk = 36
        versionCode = 3
        versionName = "2.1"
    }

    signingConfigs {
        if (keystorePropsFile.exists()) {
            create("release") {
                // storeFile 支持绝对路径，也支持相对工程根目录的路径
                storeFile = rootProject.file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            signingConfig = signingConfigs.findByName("release")
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
        }
    }

    // AGP 9 内置 Kotlin：jvmTarget 自动继承 targetCompatibility，无需单独配置
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }
}

